import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { StickerLibrary } from './sticker-lib.mjs';
import { newRequestId } from './native-sticker.mjs';
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'dafeiyu-library-'));
const library = path.join(dir,'stickers'); fs.mkdirSync(library);
fs.writeFileSync(path.join(dir,'private.txt'),'not a sticker');
fs.writeFileSync(path.join(library,'ok.png'),'fixture');
const lib = new StickerLibrary(library);
lib.meta = {stickers: {bad:{file:'../private.txt'}, good:{file:'ok.png'}}};
assert.equal(lib.find('bad'), null);
assert.deepEqual(lib.list().map(x=>x.id), ['good']);
assert.equal(lib.resolveFile(path.join(dir,'private.txt')),null);
assert.equal(newRequestId('same-intent'),newRequestId('same-intent'));
assert.notEqual(newRequestId('first'),newRequestId('second'));
assert.match(newRequestId(),/^[a-z0-9_-]{8,64}$/);
console.log('PASS 6 release security assertions');
